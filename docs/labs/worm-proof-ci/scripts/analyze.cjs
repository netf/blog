#!/usr/bin/env node
// Derive results/summary.md from the raw results/*.jsonl. No measurement happens here.
const fs = require('fs');
const path = require('path');
const LAB = path.join(__dirname, '..');
const RES = path.join(LAB, 'results');
const rd = (f) => { try { return fs.readFileSync(path.join(RES, f), 'utf8').trim().split('\n').filter(Boolean).map((l) => JSON.parse(l)); } catch (e) { return []; } };
const median = (xs) => { if (!xs.length) return NaN; const s = [...xs].sort((a, b) => a - b), m = s.length >> 1; return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2; };
const pct = (xs, p) => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
const f = (x, d = 2) => (Number.isFinite(x) ? x.toFixed(d) : 'n/a');
let out = '';
const w = (s = '') => { out += s + '\n'; };

w('# Worm-proof CI: results\n');
w('_Generated by `scripts/analyze.cjs` from the raw JSONL in this directory._\n');

const attack = rd('attack.jsonl');
if (attack.length) {
  const arms = [...new Set(attack.map((r) => r.arm))];
  w(`## Attack (N = ${attack.filter((r) => r.arm === arms[0]).length} runs per regime)\n`);
  w('| regime | worm code ran | secrets found (median) | canaries out via HTTP | via DNS | runs that self-published | workspace write | git hook | worm publish error |');
  w('|---|---|---|---|---|---|---|---|---|');
  for (const a of arms) {
    const rs = attack.filter((r) => r.arm === a), n = rs.length;
    const runs = (k) => `${rs.filter((r) => r[k] > 0 || r[k] === true).length}/${n}`;
    const errs = [...new Set(rs.map((r) => r.publish_error).filter(Boolean))].join(',') || '-';
    w(`| ${a} | ${runs('worm_ran')} | ${median(rs.map((r) => r.scan_count))} | ${median(rs.map((r) => r.canaries_http))}/3 (${runs('canaries_http')}) | ${median(rs.map((r) => r.canaries_dns))}/3 (${runs('canaries_dns')}) | ${runs('self_publish_versions')} | ${runs('workspace_write')} | ${runs('git_hook_write')} | ${errs} |`);
  }
  w('');
}

for (const [file, label] of [['overhead.jsonl', 'default Node compile cache'], ['overhead-compile-cache.jsonl', 'persistent Node compile cache per regime']]) {
const ov = rd(file).filter((r) => r.cache_state === 'warm' || r.cache_state === 'cold');
if (ov.length) {
  w(`# Overhead dataset: ${file} (${label})\n`);
  const modes = [...new Set(ov.map((r) => r.mode))];
  const projects = [...new Set(ov.map((r) => r.project))].sort();
  const allow = (p) => { try { return fs.readFileSync(path.join(LAB, 'corpus/projects', p, 'allowlist.txt'), 'utf8').trim(); } catch (e) { return ''; } };
  const med = (p, m, s) => median(ov.filter((r) => r.project === p && r.mode === m && r.cache_state === s && r.exit_code === 0).map((r) => r.install_seconds));
  for (const s of ['warm', 'cold']) {
    w(`## Install time, ${s} cache (median seconds per project)\n`);
    w(`| project | allowlist | ${modes.join(' | ')} | ${modes.slice(1).map((m) => m + ' ratio').join(' | ')} |`);
    w(`|---|---|${modes.map(() => '---|').join('')}${modes.slice(1).map(() => '---|').join('')}`);
    for (const p of projects) {
      const b = med(p, modes[0], s);
      w(`| ${p} | ${allow(p).replace(/\n/g, ', ') || '-'} | ${modes.map((m) => f(med(p, m, s), 3)).join(' | ')} | ${modes.slice(1).map((m) => f(med(p, m, s) / b)).join(' | ')} |`);
    }
    w('');
    for (const m of modes.slice(1)) {
      const groups = { all: projects, 'no allowlist': projects.filter((p) => !allow(p)), 'with allowlist': projects.filter((p) => allow(p)) };
      for (const [g, ps] of Object.entries(groups)) {
        const ratios = ps.map((p) => med(p, m, s) / med(p, modes[0], s)).filter(Number.isFinite);
        const deltas = ps.map((p) => (med(p, m, s) - med(p, modes[0], s)) * 1000).filter(Number.isFinite);
        const tb = ps.reduce((a, p) => a + med(p, modes[0], s), 0), tm = ps.reduce((a, p) => a + med(p, m, s), 0);
        w(`- ${s}, ${m} vs ${modes[0]}, ${g} (${ps.length} projects): median ratio ${f(median(ratios))}x (min ${f(Math.min(...ratios))}, max ${f(Math.max(...ratios))}); median added time ${f(median(deltas), 0)} ms (p90 ${f(pct(deltas, 0.9), 0)} ms); summed ${f(tb, 1)} s -> ${f(tm, 1)} s (${f((tm / tb - 1) * 100, 1)}%).`);
      }
    }
    w('');
  }
  w('### Install success (all timed runs)\n');
  for (const m of modes) {
    const rs = ov.filter((r) => r.mode === m);
    w(`- ${m}: ${rs.filter((r) => r.exit_code === 0).length}/${rs.length}`);
  }
  w('');
}
}

try {
  const dirs = fs.readdirSync(path.join(LAB, 'corpus/projects'));
  const lists = dirs.map((d) => fs.readFileSync(path.join(LAB, 'corpus/projects', d, 'allowlist.txt'), 'utf8').split('\n').filter(Boolean));
  const distinct = [...new Set(lists.flat())].sort();
  w('## Allowlist\n');
  w(`- Projects whose resolved tree has at least one install-script package: ${lists.filter((l) => l.length).length}/${dirs.length}.`);
  w(`- Distinct install-script packages across the corpus: ${distinct.length} (${distinct.join(', ')}).`);
  w('');
} catch (e) {}

const census = rd('script-census.jsonl');
if (census.length) {
  const ran = census.filter((r) => r.scripts_ran.length);
  w('## Script census: what `npm ci` actually ran (scripts on, --foreground-scripts)\n');
  w(`- Projects where npm ran at least one lifecycle script: ${ran.length}/${census.length} (${ran.map((r) => r.project).join(', ')}).`);
  w(`- Scripts that ran: ${[...new Set(census.flatMap((r) => r.scripts_ran))].sort().join(', ')}.`);
  w(`- Ran but not flagged hasInstallScript in the lockfile: ${[...new Set(census.flatMap((r) => r.ran_but_not_flagged))].join(', ') || 'none'}.`);
  w(`- Flagged but never ran on this platform: ${[...new Set(census.flatMap((r) => r.flagged_but_not_ran))].join(', ') || 'none'}.`);
  w(`- Install success with scripts on: ${census.filter((r) => r.exit_code === 0).length}/${census.length}.`);
  w('');
}

const ft = rd('failure-tests.jsonl');
if (ft.length) {
  w('## Failure tests\n');
  for (const t of [...new Set(ft.map((r) => r.test))]) {
    const rs = ft.filter((r) => r.test === t);
    const keys = [...new Set(rs.flatMap((r) => Object.keys(r)))].filter((k) => k !== 'test');
    w(`### ${t}\n`);
    w(`| ${keys.join(' | ')} |`);
    w(`|${keys.map(() => '---|').join('')}`);
    for (const r of rs) w(`| ${keys.map((k) => r[k] ?? '').join(' | ')} |`);
    w('');
  }
}
fs.writeFileSync(path.join(RES, 'summary.md'), out);
process.stdout.write(out);
